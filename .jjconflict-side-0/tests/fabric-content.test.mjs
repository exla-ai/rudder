import test from "node:test";
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import {
  FILE_CHUNK_BYTES, FILE_FANOUT, FILE_LAYOUT, MAX_FILE_LOGICAL_BYTES, MAX_FILE_NODE_BYTES,
  ContentFormatError, decodeFileNode, fileChildSpan, fileNodeReferences,
  unsigned, validateContentReference, validateFileChild, validateFileNode,
} from "../cloud/dist/fabric-content.js";
import { canonicalFabricMetadata, parseCanonicalFabricMetadata } from "../cloud/dist/fabric-cas.js";

const codec = { parseCanonical: parseCanonicalFabricMetadata, encodeCanonical: canonicalFabricMetadata };
const hash = (bytes) => createHash("sha256").update(bytes).digest("hex");
const reference = (kind, size, digit = "1") => ({ kind, algorithm: "sha256", digest: digit.repeat(64), size_bytes: BigInt(size) });
const node = (level, size, children) => ({ format_version: 1, layout: FILE_LAYOUT, level, logical_size: BigInt(size), children });
const fileReference = (value) => { const bytes = canonicalFabricMetadata(value); return { kind: "file", algorithm: "sha256", digest: hash(bytes), size_bytes: BigInt(bytes.length) }; };
const fullChunk = reference("blob", FILE_CHUNK_BYTES);
const tail = reference("blob", 3, "2");
const leaf = node(0, BigInt(FILE_CHUNK_BYTES) + 3n, [fullChunk, tail]);
const small = node(0, 3n, [tail]);
const full = node(0, BigInt(FILE_CHUNK_BYTES) * BigInt(FILE_FANOUT), Array(FILE_FANOUT).fill(fullChunk));
const branch = node(1, full.logical_size + 3n, [fileReference(full), fileReference(small)]);
const fullBranch = node(1, full.logical_size * BigInt(FILE_FANOUT), Array(FILE_FANOUT).fill(fileReference(full)));
const compact = node(2, fullBranch.logical_size + 3n, [fileReference(fullBranch), fileReference(small)]);
const placeholder = reference("file", 4096, "3");
const first = node(4, 1n << 62n, Array(FILE_FANOUT).fill(placeholder));
const last = node(4, (1n << 62n) - 1n, Array(FILE_FANOUT).fill(placeholder));
const maximum = node(5, MAX_FILE_LOGICAL_BYTES, [fileReference(first), fileReference(last)]);

// Generated by Rust 1.99.1 using the actual engine::content::FileNode,
// FileNode::validate, protocol::canonical_json and ObjectRef::from_bytes.
// These hashes bind the full serialized nodes, including their computed child
// descriptor refs, without embedding hundreds of repetitive reference entries.
const rustGolden = [
  ["leaf", leaf, "d5cd3760f66ed047157984038d81448fb01dee3373ca47416687476d7d8574be"],
  ["branch", branch, "91d1c598f27ade55f5e0b42b787413b9881748fd1dce931d918527148fc0ceca"],
  ["compact", compact, "eeab8ed1e222c0f1c2fdc1de2eb79456cfd304eb7c08eb7f5025e19fa8b03d01"],
  ["maximum", maximum, "4076896cbf11e826d595b6964fadf964c31a9108e7a5e564cd7f6540710bc44d"],
  ["above_safe_integer", node(3, (1n << 53n) + 17n, Array(129).fill(placeholder)), "3ba58bf9f2c5f7388903dbea5b6545130097ec2f2653ed14621aaae54be0e3d1"],
  ["repeated", node(0, 2n * BigInt(FILE_CHUNK_BYTES), [fullChunk, fullChunk]), "10f49be2822019071c79d3bc8f27f06c49d2df17bada1facb3a6e1f24031a281"],
];

test("file nodes match actual Rust canonical serialization goldens", () => {
  for (const [name, value, digest] of rustGolden) {
    const bytes = canonicalFabricMetadata(value);
    assert.equal(hash(bytes), digest, name);
    const decoded = decodeFileNode(bytes, codec);
    assert.deepEqual(decoded, value, name);
    assert.deepEqual(fileNodeReferences(bytes, codec), value.children, name);
    assert.equal(typeof decoded.logical_size, "bigint");
    assert.ok(decoded.children.every((child) => typeof child.size_bytes === "bigint"));
  }
});

test("logical sizes above 2^53 and through i64::MAX never round through Number", () => {
  const above = rustGolden.find(([name]) => name === "above_safe_integer")[1];
  assert.equal(decodeFileNode(canonicalFabricMetadata(above), codec).logical_size, 9_007_199_254_741_009n);
  const decoded = decodeFileNode(canonicalFabricMetadata(maximum), codec);
  assert.equal(decoded.logical_size, 9_223_372_036_854_775_807n);
  assert.equal(fileChildSpan(decoded, 0), 1n << 62n);
  assert.equal(fileChildSpan(decoded, 1), (1n << 62n) - 1n);
  validateFileChild(decoded, 0, first); validateFileChild(decoded, 1, last);
  assert.throws(() => validateFileChild(decoded, 1, first), ContentFormatError);
  assert.throws(() => decodeFileNode(canonicalFabricMetadata(maximum), { ...codec, parseCanonical: (bytes) => JSON.parse(bytes.toString()) }), ContentFormatError);
  assert.throws(() => unsigned(Number.MAX_SAFE_INTEGER + 1), ContentFormatError);
});

test("compact last subtrees use minimal levels and exact parent spans", () => {
  validateFileChild(branch, 0, full); validateFileChild(branch, 1, small);
  validateFileChild(compact, 0, fullBranch); validateFileChild(compact, 1, small);
  assert.equal(compact.level, 2); assert.equal(small.level, 0, "the right edge skips an unneeded level");
  for (const malformed of [node(0, 2n, [reference("blob", 2)]), full, { ...small, level: 1 }]) assert.throws(() => validateFileChild(branch, 1, malformed), ContentFormatError);
  assert.throws(() => validateFileChild(leaf, 0, small), ContentFormatError);
  for (const index of [-1, 2, 0.5, NaN, Infinity]) assert.throws(() => validateFileChild(branch, index, small), ContentFormatError);
});

test("every supported level is minimal and may have a one-byte compact tail", () => {
  const one = node(0, 1n, [reference("blob", 1)]);
  let previousCapacity = BigInt(FILE_CHUNK_BYTES);
  for (let level = 0; level <= 5; level++) {
    const capacity = level === 0 ? BigInt(FILE_CHUNK_BYTES) : previousCapacity;
    if (level === 0) {
      validateFileNode(node(0, capacity + 1n, [fullChunk, reference("blob", 1)]));
    } else {
      const left = node(level - 1, capacity, level === 1 ? Array(FILE_FANOUT).fill(fullChunk) : Array(FILE_FANOUT).fill(placeholder));
      const parent = node(level, capacity + 1n, [fileReference(left), fileReference(one)]);
      validateFileNode(parent); validateFileChild(parent, 0, left); validateFileChild(parent, 1, one);
      assert.throws(() => validateFileNode({ ...parent, level: level - 1 }), ContentFormatError);
    }
    previousCapacity = BigInt(FILE_CHUNK_BYTES) * BigInt(FILE_FANOUT) ** BigInt(level + 1);
  }
  assert.throws(() => validateFileNode({ ...maximum, level: 6 }), ContentFormatError);
});

test("repeated chunks and descriptor refs preserve ordered logical multiplicity", () => {
  const repeated = validateFileNode(node(0, 2n * BigInt(FILE_CHUNK_BYTES), [fullChunk, fullChunk]));
  assert.deepEqual(repeated.children[0], repeated.children[1]);
  assert.equal(repeated.logical_size, 2n * fullChunk.size_bytes);
  const repeatedTree = node(1, 2n * full.logical_size, [fileReference(full), fileReference(full)]);
  validateFileChild(repeatedTree, 0, full); validateFileChild(repeatedTree, 1, full);
  assert.equal(fileNodeReferences(canonicalFabricMetadata(repeatedTree), codec).length, 2);
});

test("schema checks reject unsupported fields, layouts, counts, kinds and lengths", () => {
  const failures = [
    null, [], {}, { ...leaf, hidden_reference: fullChunk }, { ...leaf, layout: "private unqualified layout" },
    { ...leaf, format_version: 2 }, { ...leaf, level: 255 }, { ...leaf, logical_size: 0n },
    { ...maximum, logical_size: MAX_FILE_LOGICAL_BYTES + 1n }, { ...leaf, logical_size: -1n },
    { ...leaf, children: [] }, { ...leaf, children: Array(FILE_FANOUT + 1).fill(fullChunk) },
    { ...leaf, children: [tail, fullChunk] }, { ...leaf, logical_size: leaf.logical_size + 1n },
    { ...leaf, children: [reference("file", FILE_CHUNK_BYTES), tail] },
    { ...leaf, children: [{ ...fullChunk, size_bytes: BigInt(FILE_CHUNK_BYTES) + 1n }, tail] },
    { ...branch, children: [{ ...branch.children[0], size_bytes: 0n }, branch.children[1]] },
    { ...branch, children: [{ ...branch.children[0], size_bytes: BigInt(MAX_FILE_NODE_BYTES) + 1n }, branch.children[1]] },
    { ...leaf, children: [{ ...fullChunk, hidden: true }, tail] },
    { ...leaf, children: [{ ...fullChunk, digest: "A".repeat(64) }, tail] },
    { ...leaf, children: [{ ...fullChunk, algorithm: "sha1" }, tail] },
    { ...leaf, children: [{ ...fullChunk, kind: "unknown" }, tail] },
  ];
  for (const value of failures) assert.throws(() => validateFileNode(value), ContentFormatError);
});

test("raw metadata limits and canonical codec checks precede graph admission", () => {
  let parsed = false;
  assert.throws(() => decodeFileNode(Buffer.alloc(MAX_FILE_NODE_BYTES + 1, 0x20), { ...codec, parseCanonical: () => { parsed = true; return leaf; } }), ContentFormatError);
  assert.equal(parsed, false);
  const bytes = canonicalFabricMetadata(leaf);
  for (const raw of [Buffer.concat([Buffer.from(" "), bytes]), Buffer.concat([bytes, Buffer.from("\n")]),
    Buffer.from(bytes.toString().replace('"level":0', '"level":0.0')),
    Buffer.from(bytes.toString().replace('"level":0', '"level":0,"level":0')),
    Buffer.from(bytes.toString().replace('"size_bytes":4194304', '"size_bytes":4194304,"size_bytes":4194304'))]) assert.throws(() => decodeFileNode(raw, codec));
  assert.throws(() => decodeFileNode(bytes, { ...codec, encodeCanonical: () => Buffer.from("{}") }), ContentFormatError);
});

test("reference format limits remain independent of Cloud object-size quotas", () => {
  const huge = reference("blob", (1n << 64n) - 1n);
  assert.equal(validateContentReference(huge).size_bytes, (1n << 64n) - 1n);
  for (const kind of ["blob", "file", "directory", "directory_shard", "source_root", "environment_root", "checkpoint", "action_key", "action_result"]) assert.equal(validateContentReference(reference(kind, 1)).kind, kind);
  for (const value of [-1, -0, 1.5, NaN, Infinity, "1", true, 1n << 64n]) assert.throws(() => unsigned(value), ContentFormatError);
  assert.throws(() => unsigned(2n, 1n), ContentFormatError);
  assert.equal(unsigned(1, 1), 1n);
  assert.throws(() => validateContentReference({ ...huge, size_bytes: 1n << 64n }), ContentFormatError);
  assert.throws(() => validateContentReference({ ...huge, size_bytes: Number.MAX_SAFE_INTEGER + 1 }), ContentFormatError);
  // Chunk-format bounds still reject huge raw references inside a File leaf.
  assert.throws(() => validateFileNode(node(0, 1n, [huge])), ContentFormatError);
});
