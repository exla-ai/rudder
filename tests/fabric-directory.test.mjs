const wideBranch = () => {
  const make = (prefix) => leaf(Array.from({ length: 4 }, (_, index) => ({ name_hex: raw(`${prefix}${index}`), node: { type: "symlink", target_hex: "ab".repeat(4096) } })));
  const a = make("a"), b = make("b"), parent = branch("", [link(98, a), link(99, b)]);
  return { a, b, parent };
};

test("swapped equal-summary pages and forged summaries fail graph validation", () => {
  const { a, b, parent } = wideBranch();
  validateDirectoryShard(parent.value, codec);
  validateDirectoryChild("directory_shard", parent.value, a.reference, a.value, codec);
  validateDirectoryChild("directory_shard", parent.value, b.reference, b.value, codec);
  const swapped = branch("", [link(98, b), link(99, a)]);
  validateDirectoryShard(swapped.value, codec);
  assert.throws(() => validateDirectoryChild("directory_shard", swapped.value, b.reference, b.value, codec), /radix range/);
  const counts = structuredClone(parent.value);
  counts.node.children[0].shard.summary.entry_count++;
  counts.summary.entry_count++;
  validateDirectoryShard(counts, codec);
  assert.throws(() => validateDirectoryChild("directory_shard", counts, a.reference, a.value, codec), /summary/);
  const wrongValue = structuredClone(a.value);
  wrongValue.node.entries[0].node.target_hex = "ac".repeat(4096);
  assert.throws(() => validateDirectoryChild("directory_shard", parent.value, a.reference, wrongValue, codec), /typed reference/);
  assert.throws(() => validateDirectoryChild("directory_shard", parent.value, { ...a.reference, size_bytes: a.reference.size_bytes + 1n }, a.value, codec));
});

test("duplicate shard aliases fail locally while repeated File refs check every logical size", () => {
  const { a } = wideBranch();
  const alias = branch("", [link(98, a), link(99, a)]);
  assert.throws(() => validateDirectoryShard(alias.value, codec), /repeats/);
  assert.throws(() => validateDirectoryChild("directory_shard", alias.value, a.reference, a.value, codec));
  const descriptor = validateContentReference(RUST_GOLDEN.file_reference), value = codec.parseCanonical(Buffer.from(RUST_GOLDEN.file_json));
  assert.notEqual(descriptor.size_bytes, 3n);
  const good = leaf([file("a", descriptor, 3n), file("b", descriptor, 3n)]);
  validateDirectoryChild("directory_shard", good.value, descriptor, value, codec);
  const bad = leaf([file("a", descriptor, 3n), file("b", descriptor, descriptor.size_bytes)]);
  validateDirectoryShard(bad.value, codec);
  assert.throws(() => validateDirectoryChild("directory_shard", bad.value, descriptor, value, codec), /logical size/);
  assert.throws(() => validateDirectoryChild("directory_shard", good.value, descriptor, { ...value, logical_size: 4n }, codec), /typed reference/);
});

