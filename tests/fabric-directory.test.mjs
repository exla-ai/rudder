test("Rust-produced directory v2 bytes, raw names, modes and typed references round trip exactly", () => {
  for (const row of RUST_GOLDEN.rows) {
    const bytes = Buffer.from(row.json);
    assert.equal(hash(bytes), row.reference.digest, row.label);
    assert.equal(bytes.length, row.reference.size_bytes, row.label);
    const decoded = row.reference.kind === "directory" ? decodeDirectoryRoot(bytes, codec) : decodeDirectoryShard(bytes, codec);
    assert.deepEqual(codec.encodeCanonical(decoded), bytes, row.label);
    assert.deepEqual(directoryReferences(row.reference.kind, codec.parseCanonical(bytes), codec), row.references.map(validateContentReference), row.label);
  }
  const mixed = decodeDirectoryShard(Buffer.from(golden("mixed_shard").json), codec);
  assert.equal(mixed.summary.entry_count, 4n);
  assert.equal(mixed.summary.subdirectory_count, 1n);
  assert.deepEqual(mixed.node.entries.map((entry) => entry.name_hex), ["61", "6161", "80", "ff"]);
  assert.equal(mixed.node.entries[2].node.mode, 0o4755);
  assert.equal(mixed.node.entries[1].node.target_hex, "2e2e2fff");
  assert.equal(decodeDirectoryRoot(Buffer.from(golden("mixed_root").json), codec).mode, 0o2755);
});

test("full u64 counters and logical lengths above 2^53 remain lossless, independently of Cloud quotas", () => {
  const header = golden("staged_u64_header"), parsed = decodeDirectoryRoot(Buffer.from(header.json), codec);
  assert.equal(parsed.entry_count, 18446744073709551615n);
  assert.equal(parsed.subdirectory_count, 18446744073709551614n);
  assert.deepEqual(codec.encodeCanonical(parsed), Buffer.from(header.json));
  const shard = decodeDirectoryShard(Buffer.from(golden("staged_big_logical_shard").json), codec);
  assert.equal(shard.node.entries[0].node.logical_size, 9007199254740993n);
  assert.equal(shard.node.entries[0].node.object.size_bytes, 22n);
  const largeBlob = { kind: "blob", algorithm: "sha256", digest: "a".repeat(64), size_bytes: 256n * 1024n * 1024n + 1n };
  assert.equal(validateDirectoryEntry(file("legacy-large", largeBlob)).node.logical_size, largeBlob.size_bytes);
  const largeDirectory = { ...largeBlob, kind: "directory", size_bytes: (1n << 64n) - 1n };
  const directory = leaf([{ name_hex: "61", node: { type: "directory", object: largeDirectory } }]);
  assert.equal(validateDirectoryShard(directory.value, codec).node.entries[0].node.object.size_bytes, largeDirectory.size_bytes);
  assert.throws(() => validateDirectoryRoot({ ...header.value, entry_count: Number.MAX_SAFE_INTEGER + 1 }, codec));
  assert.throws(() => validateDirectoryRoot({ ...header.value, entry_count: 1n << 64n }, codec));
  assert.throws(() => validateDirectoryRoot({ ...header.value, entry_count: -1n }, codec));
});

